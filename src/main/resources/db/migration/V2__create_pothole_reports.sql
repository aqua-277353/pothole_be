CREATE TABLE pothole_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    region VARCHAR(100) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    source VARCHAR(20) NOT NULL,
    image_url VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    confirm_count INTEGER NOT NULL DEFAULT 1,
    detected_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_pothole_reports_user
        FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT chk_pothole_lat
        CHECK (lat >= -90 AND lat <= 90),
    CONSTRAINT chk_pothole_lng
        CHECK (lng >= -180 AND lng <= 180),
    CONSTRAINT chk_pothole_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT chk_pothole_source
        CHECK (source IN ('SENSOR', 'MANUAL')),
    CONSTRAINT chk_pothole_status
        CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT chk_pothole_confirm_count
        CHECK (confirm_count >= 1)
);

CREATE INDEX idx_pothole_region_lat_lng
    ON pothole_reports(region, lat, lng);
